// Emits <Name>Language.g.cs: the tables of a GrammarModel as RVA literals
// (ReadOnlySpan<ushort/uint/byte> properties), struct tables packed as primitives and
// decoded with TreeSitter.Abi.TableDecoder, strings as C# literals. The output depends only
// on the model and the options (no dates, no tool version), with '\n' line endings.

using System.Globalization;
using System.Text;
using TreeSitter.Abi;
using TreeSitter.Generator.Lex;
using TreeSitter.Generator.Model;

namespace TreeSitter.Generator.Emit;

/// <summary>Options of the C# emitters.</summary>
public sealed record EmitOptions(string GrammarName, string Namespace, string? SourceDescription);

/// <summary>Emits the C# source of one grammar.</summary>
public interface ITableEmitter
{
    string Emit(GrammarModel model, EmitOptions options);
}

/// <summary>Tables as literals in the assembly (option "literal").</summary>
public sealed class LiteralEmitter : ITableEmitter
{
    private const int ValuesPerLine = 16;

    public string Emit(GrammarModel model, EmitOptions options)
    {
        ArgumentNullException.ThrowIfNull(model);
        ArgumentNullException.ThrowIfNull(options);
        LanguageTables t = model.Tables;
        var w = new CodeWriter();
        string className = options.GrammarName + "Grammar";

        w.Line("// <auto-generated/>");
        w.Line($"// Generated by ts2cs from {options.SourceDescription ?? "parser.c"}. Do not edit.");
        w.Line();
        w.Line("#nullable enable");
        w.Line();
        w.Line("using System;");
        w.Line("using System.ComponentModel;");
        w.Line("using System.IO;");
        w.Line("using TreeSitter.Abi;");
        w.Line();
        w.Line($"namespace {options.Namespace};");
        w.Line();
        w.Line($"/// <summary>The {options.GrammarName} grammar.</summary>");
        w.Line($"public static class {className}");
        w.Line("{");
        w.Indent++;
        w.Line("private static readonly Lazy<Language> LazyLanguage = new(() => Language.FromTables(CreateTables()));");
        w.Line();
        w.Line("/// <summary>The language (created on first use, shared).</summary>");
        w.Line("public static Language Language => LazyLanguage.Value;");
        w.Line();
        w.Line("/// <summary>");
        w.Line("/// A query file of the grammar (queries/&lt;name&gt;.scm, embedded in the assembly), for");
        w.Line("/// example \"highlights\"; null when the grammar has no such file.");
        w.Line("/// </summary>");
        w.Line("public static string? Query(string name)");
        w.Line("{");
        w.Indent++;
        w.Line($"using Stream? stream = typeof({className}).Assembly.GetManifestResourceStream(\"queries/\" + name + \".scm\");");
        w.Line("if (stream is null)");
        w.Line("{");
        w.Indent++;
        w.Line("return null;");
        w.Indent--;
        w.Line("}");
        w.Line();
        w.Line("using StreamReader reader = new StreamReader(stream);");
        w.Line("return reader.ReadToEnd();");
        w.Indent--;
        w.Line("}");
        w.Line();
        w.Line("/// <summary>Part of the grammar ABI: creates new table objects on every call.</summary>");
        w.Line("[EditorBrowsable(EditorBrowsableState.Never)]");
        w.Line("public static LanguageTables CreateTables() => new()");
        w.Line("{");
        w.Indent++;
        Scalar(w, nameof(t.AbiVersion), t.AbiVersion);
        Scalar(w, nameof(t.SymbolCount), t.SymbolCount);
        Scalar(w, nameof(t.AliasCount), t.AliasCount);
        Scalar(w, nameof(t.TokenCount), t.TokenCount);
        Scalar(w, nameof(t.ExternalTokenCount), t.ExternalTokenCount);
        Scalar(w, nameof(t.StateCount), t.StateCount);
        Scalar(w, nameof(t.LargeStateCount), t.LargeStateCount);
        Scalar(w, nameof(t.ProductionIdCount), t.ProductionIdCount);
        Scalar(w, nameof(t.FieldCount), t.FieldCount);
        Scalar(w, nameof(t.MaxAliasSequenceLength), t.MaxAliasSequenceLength);
        Scalar(w, nameof(t.KeywordCaptureToken), t.KeywordCaptureToken);
        Scalar(w, nameof(t.MaxReservedWordSetSize), t.MaxReservedWordSetSize);
        Scalar(w, nameof(t.SupertypeCount), t.SupertypeCount);
        w.Line($"Name = {StringLiteral(t.Name)},");
        w.Line($"Metadata = new LanguageMetadata({t.Metadata.MajorVersion}, {t.Metadata.MinorVersion}, {t.Metadata.PatchVersion}),");
        Assign(w, nameof(t.ParseTable), t.ParseTable, "ParseTableData.ToArray()");
        Assign(w, nameof(t.SmallParseTable), t.SmallParseTable, "SmallParseTableData.ToArray()");
        Assign(w, nameof(t.SmallParseTableMap), t.SmallParseTableMap, "SmallParseTableMapData.ToArray()");
        Assign(w, nameof(t.ParseActions), t.ParseActions, "TableDecoder.ParseActions(ParseActionsData)");
        Assign(w, nameof(t.SymbolNames), t.SymbolNames, "SymbolNamesData()");
        Assign(w, nameof(t.FieldNames), t.FieldNames, "FieldNamesData()");
        Assign(w, nameof(t.FieldMapSlices), t.FieldMapSlices, "TableDecoder.MapSlices(FieldMapSlicesData)");
        Assign(w, nameof(t.FieldMapEntries), t.FieldMapEntries, "TableDecoder.FieldMapEntries(FieldMapEntriesData)");
        Assign(w, nameof(t.SymbolMetadata), t.SymbolMetadata, "TableDecoder.SymbolMetadata(SymbolMetadataData)");
        Assign(w, nameof(t.PublicSymbolMap), t.PublicSymbolMap, "PublicSymbolMapData.ToArray()");
        Assign(w, nameof(t.AliasMap), t.AliasMap, "AliasMapData.ToArray()");
        Assign(w, nameof(t.AliasSequences), t.AliasSequences, "AliasSequencesData.ToArray()");
        Assign(w, nameof(t.LexModes), t.LexModes, "TableDecoder.LexerModes(LexModesData)");
        Assign(w, nameof(t.PrimaryStateIds), t.PrimaryStateIds, "PrimaryStateIdsData.ToArray()");
        Assign(w, nameof(t.ReservedWords), t.ReservedWords, "ReservedWordsData.ToArray()");
        Assign(w, nameof(t.SupertypeSymbols), t.SupertypeSymbols, "SupertypeSymbolsData.ToArray()");
        Assign(w, nameof(t.SupertypeMapSlices), t.SupertypeMapSlices, "TableDecoder.MapSlices(SupertypeMapSlicesData)");
        Assign(w, nameof(t.SupertypeMapEntries), t.SupertypeMapEntries, "SupertypeMapEntriesData.ToArray()");
        Assign(w, nameof(t.ExternalScannerStates), t.ExternalScannerStates, "TableDecoder.Booleans(ExternalScannerStatesData)");
        Assign(w, nameof(t.ExternalScannerSymbolMap), t.ExternalScannerSymbolMap, "ExternalScannerSymbolMapData.ToArray()");
        if (model.LexFunction is not null)
        {
            w.Line("LexFn = Lex,");
        }
        if (model.KeywordLexFunction is not null)
        {
            w.Line("KeywordLexFn = LexKeywords,");
        }
        Flag(w, nameof(t.ExternalScannerCreateIsSet), t.ExternalScannerCreateIsSet);
        Flag(w, nameof(t.ExternalScannerDestroyIsSet), t.ExternalScannerDestroyIsSet);
        Flag(w, nameof(t.ExternalScannerScanIsSet), t.ExternalScannerScanIsSet);
        Flag(w, nameof(t.ExternalScannerSerializeIsSet), t.ExternalScannerSerializeIsSet);
        Flag(w, nameof(t.ExternalScannerDeserializeIsSet), t.ExternalScannerDeserializeIsSet);
        if (t.ExternalScannerCreateIsSet)
        {
            // The scanner is the hand-written <Name>Scanner class of the grammar assembly.
            w.Line($"ExternalScannerCreate = static () => new {options.GrammarName}Scanner(),");
        }
        w.Indent--;
        w.Line("};");

        var lexData = new List<LexData>();
        var programs = new List<LexProgram>();
        if (model.Lex is not null)
        {
            EmitLex(w, LexEmitter.Emit(model.Lex, "Lex", model.SymbolValues, model.CharacterSets), lexData);
            programs.Add(model.Lex);
        }
        if (model.KeywordLex is not null)
        {
            EmitLex(w, LexEmitter.Emit(model.KeywordLex, "LexKeywords", model.SymbolValues, model.CharacterSets), lexData);
            programs.Add(model.KeywordLex);
        }
        lexData.AddRange(LexEmitter.EmitCharacterSets(programs, model.CharacterSets));
        foreach (LexData data in lexData)
        {
            Numbers(w, data.ElementType, data.Name, data.Values);
        }

        Words(w, "ParseTableData", t.ParseTable);
        Words(w, "SmallParseTableData", t.SmallParseTable);
        if (t.SmallParseTableMap is not null)
        {
            Numbers(w, "uint", "SmallParseTableMapData", t.SmallParseTableMap.Select(v => (ulong)v));
        }
        if (t.ParseActions is not null)
        {
            var words = new List<ushort>(t.ParseActions.Length * 4);
            foreach (ParseActionEntry entry in t.ParseActions)
            {
                var (w0, w1, w2, w3) = entry.ToRaw();
                words.AddRange([w0, w1, w2, w3]);
            }
            Words(w, "ParseActionsData", words);
        }
        Strings(w, "SymbolNamesData", t.SymbolNames);
        Strings(w, "FieldNamesData", t.FieldNames);
        if (t.FieldMapSlices is not null)
        {
            Words(w, "FieldMapSlicesData", t.FieldMapSlices.SelectMany(s => new[] { s.Index, s.Length }));
        }
        if (t.FieldMapEntries is not null)
        {
            Words(w, "FieldMapEntriesData", t.FieldMapEntries.SelectMany(e => new[] { e.FieldId, (ushort)(e.ChildIndex | (e.Inherited ? 0x100 : 0)) }));
        }
        if (t.SymbolMetadata is not null)
        {
            Numbers(w, "byte", "SymbolMetadataData", t.SymbolMetadata.Select(m => (ulong)((m.Visible ? 1 : 0) | (m.Named ? 2 : 0) | (m.Supertype ? 4 : 0))));
        }
        Words(w, "PublicSymbolMapData", t.PublicSymbolMap);
        Words(w, "AliasMapData", t.AliasMap);
        Words(w, "AliasSequencesData", t.AliasSequences);
        if (t.LexModes is not null)
        {
            Words(w, "LexModesData", t.LexModes.SelectMany(m => new[] { m.LexState, m.ExternalLexState, m.ReservedWordSetId }));
        }
        Words(w, "PrimaryStateIdsData", t.PrimaryStateIds);
        Words(w, "ReservedWordsData", t.ReservedWords);
        Words(w, "SupertypeSymbolsData", t.SupertypeSymbols);
        if (t.SupertypeMapSlices is not null)
        {
            Words(w, "SupertypeMapSlicesData", t.SupertypeMapSlices.SelectMany(s => new[] { s.Index, s.Length }));
        }
        Words(w, "SupertypeMapEntriesData", t.SupertypeMapEntries);
        if (t.ExternalScannerStates is not null)
        {
            Numbers(w, "byte", "ExternalScannerStatesData", t.ExternalScannerStates.Select(b => b ? 1UL : 0UL));
        }
        Words(w, "ExternalScannerSymbolMapData", t.ExternalScannerSymbolMap);

        w.Indent--;
        w.Line("}");
        return w.ToString();
    }

    private static void Scalar(CodeWriter w, string name, ulong value) =>
        w.Line($"{name} = {value.ToString(CultureInfo.InvariantCulture)},");

    private static void Flag(CodeWriter w, string name, bool value)
    {
        if (value)
        {
            w.Line($"{name} = true,");
        }
    }

    // A null table stays null (C NULL), so the property is not assigned.
    private static void Assign(CodeWriter w, string name, object? table, string expression)
    {
        if (table is not null)
        {
            w.Line($"{name} = {expression},");
        }
    }

    private static void EmitLex(CodeWriter w, LexEmitResult result, List<LexData> data)
    {
        w.Line();
        foreach (string line in result.MethodLines)
        {
            w.Line(line);
        }
        data.AddRange(result.Data);
    }

    private static void Words(CodeWriter w, string name, IEnumerable<ushort>? values)
    {
        if (values is not null)
        {
            Numbers(w, "ushort", name, values.Select(v => (ulong)v));
        }
    }

    private static void Numbers(CodeWriter w, string type, string name, IEnumerable<ulong> values)
    {
        w.Line();
        w.Line($"private static ReadOnlySpan<{type}> {name} =>");
        w.Line("[");
        w.Indent++;
        var line = new StringBuilder();
        int count = 0;
        foreach (ulong value in values)
        {
            if (count > 0)
            {
                line.Append(count % ValuesPerLine == 0 ? "" : " ");
            }
            line.Append(value.ToString(CultureInfo.InvariantCulture)).Append(',');
            count++;
            if (count % ValuesPerLine == 0)
            {
                w.Line(line.ToString());
                line.Clear();
            }
        }
        if (line.Length > 0)
        {
            w.Line(line.ToString());
        }
        w.Indent--;
        w.Line("];");
    }

    private static void Strings(CodeWriter w, string name, string?[]? values)
    {
        if (values is null)
        {
            return;
        }
        w.Line();
        w.Line($"private static string?[] {name}() =>");
        w.Line("[");
        w.Indent++;
        foreach (string? value in values)
        {
            w.Line(StringLiteral(value) + ",");
        }
        w.Indent--;
        w.Line("];");
    }

    /// <summary>C# literal of a string; every char that is not printable ASCII becomes \uXXXX.</summary>
    internal static string StringLiteral(string? value)
    {
        if (value is null)
        {
            return "null";
        }
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('"');
        foreach (char c in value)
        {
            switch (c)
            {
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\\':
                    sb.Append("\\\\");
                    break;
                default:
                    if (c < 0x20 || c > 0x7e)
                    {
                        sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(c);
                    }
                    break;
            }
        }
        sb.Append('"');
        return sb.ToString();
    }

    private sealed class CodeWriter
    {
        private readonly StringBuilder _text = new();

        public int Indent { get; set; }

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                _text.Append(' ', Indent * 4).Append(text);
            }
            _text.Append('\n');
        }

        public override string ToString() => _text.ToString();
    }
}

/// <summary>Tables as a compressed embedded resource (option "blob"); not implemented yet (M2).</summary>
public sealed class BlobEmitter : ITableEmitter
{
    public string Emit(GrammarModel model, EmitOptions options) =>
        throw new NotSupportedException("--tables=blob is not implemented yet");
}
