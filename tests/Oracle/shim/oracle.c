/* ---------------------------------------------------------------------------
 * Growable string buffer.
 */

typedef struct {
    char *data;
    size_t size;
    size_t capacity;
} StringBuilder;

static void *xmalloc(size_t size)
{
    void *p = malloc(size);
    if (p == NULL && size > 0) {
        abort();
    }
    return p;
}

static void sb_init(StringBuilder *sb)
{
    sb->data = NULL;
    sb->size = 0;
    sb->capacity = 0;
}

static void sb_destroy(StringBuilder *sb)
{
    free(sb->data);
    sb->data = NULL;
    sb->size = 0;
    sb->capacity = 0;
}

static bool sb_grow(StringBuilder *sb, size_t extra)
{
    size_t needed = sb->size + extra + 1;
    if (needed <= sb->capacity) {
        return true;
    }
    size_t capacity = sb->capacity == 0 ? 256 : sb->capacity;
    while (capacity < needed) {
        capacity *= 2;
    }
    char *data = (char *)xmalloc(capacity);
    if (sb->data != NULL) {
        memcpy(data, sb->data, sb->size);
        free(sb->data);
    }
    sb->data = data;
    sb->capacity = capacity;
    return true;
}

static bool sb_put(StringBuilder *sb, const char *text, size_t length)
{
    if (!sb_grow(sb, length)) {
        return false;
    }
    memcpy(sb->data + sb->size, text, length);
    sb->size += length;
    sb->data[sb->size] = '\0';
    return true;
}

static bool sb_putc(StringBuilder *sb, char c)
{
    return sb_put(sb, &c, 1);
}

static bool sb_fmt(StringBuilder *sb, const char *format, ...)
{
    char stack_buffer[256];
    va_list args;
    va_start(args, format);
    int needed = vsnprintf(stack_buffer, sizeof(stack_buffer), format, args);
    va_end(args);
    if (needed < 0) {
        return false;
    }
    if ((size_t)needed < sizeof(stack_buffer)) {
        return sb_put(sb, stack_buffer, (size_t)needed);
    }
    char *heap_buffer = (char *)xmalloc((size_t)needed + 1);
    va_start(args, format);
    needed = vsnprintf(heap_buffer, (size_t)needed + 1, format, args);
    va_end(args);
    bool ok = false;
    if (needed >= 0) {
        ok = sb_put(sb, heap_buffer, (size_t)needed);
    }
    free(heap_buffer);
    return ok;
}

static bool sb_put_string_or_null(StringBuilder *sb, const char *s)
{
    if (s == NULL) {
        return sb_put(sb, "null", 4);
    }
    if (!sb_putc(sb, '"')) {
        return false;
    }
    for (const unsigned char *p = (const unsigned char *)s; *p != '\0'; p++) {
        unsigned char c = *p;
        switch (c) {
        case '"':
            if (!sb_put(sb, "\\\"", 2)) return false;
            break;
        case '\\':
            if (!sb_put(sb, "\\\\", 2)) return false;
            break;
        case '\n':
            if (!sb_put(sb, "\\n", 2)) return false;
            break;
        case '\t':
            if (!sb_put(sb, "\\t", 2)) return false;
            break;
        default:
            if (c < 0x20 || c >= 0x7f) {
                if (!sb_fmt(sb, "\\x%02x", c)) return false;
            } else {
                if (!sb_putc(sb, (char)c)) return false;
            }
            break;
        }
    }
    return sb_putc(sb, '"');
}

