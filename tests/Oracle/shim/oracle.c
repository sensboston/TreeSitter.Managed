/* Oracle test harness shim.
 *
 * Native exports over the pinned tree-sitter runtime and the regenerated
 * grammars. Test only, never shipped.
 *
 * Exports (all exported on every platform):
 *   const TSLanguage *oracle_language(const char *name)
 *   char           *oracle_dump_tables(const TSLanguage *lang)
 *   char           *oracle_dump_language_api(const TSLanguage *lang)
 *   char           *oracle_subtree_script(const char *script)
 *   char           *oracle_lexer_script(const char *script)
 *   void            oracle_free(char *p)
 *   uint32_t        oracle_abi_version(const TSLanguage *lang)
 *   uint32_t        oracle_decode(int encoding, const uint8_t *buf, uint32_t len, int32_t *code_point)
 *   char           *oracle_parser_dot_graphs(const char *grammar, const uint8_t *input, uint32_t length)
 *   char           *oracle_tree_dot_graph(const char *grammar, const uint8_t *input, uint32_t length)
 *
 * The list of available grammars is defined in oracle_grammars.c, which is
 * generated by tools/build-oracle.sh from the upstream directory of each
 * grammar under grammars/.
 *
 * The text formats of the two dumps are described in tests/Oracle/FORMATS.md.
 * The format of the subtree script and of the lexer script is described there
 * too, in the sections "Subtree script" and "Lexer script".
 */

