static void TDumpNode(ScriptState *state, TSNode node, uint32_t depth) {
    if (ts_node_is_null(node)) return;

    for (uint32_t i = 0; i < depth; i++) sb_fmt(state->out, "  ");
    sb_fmt(state->out, "type=%s start_byte=%u start_point=%u:%u end_byte=%u end_point=%u:%u\n",
        ts_node_type(node),
        ts_node_start_byte(node),
        (unsigned)ts_node_start_point(node).row, (unsigned)ts_node_start_point(node).column,
        ts_node_end_byte(node),
        (unsigned)ts_node_end_point(node).row, (unsigned)ts_node_end_point(node).column);

    uint32_t child_count = ts_node_child_count(node);
    for (uint32_t i = 0; i < child_count; i++) {
        TDumpNode(state, ts_node_child(node, i), depth + 1);
    }
}

static void TDump(ScriptState *state, uint32_t line_number) {
    if (state->tree == NULL) {
        script_error(state, line_number, "no tree created");
        return;
    }
    TDumpNode(state, ts_tree_root_node(state->tree), 0);
}

/* A range is sb:sr:sc-eb:er:ec, as in the lexer script. */
static bool script_parse_range(const char *text, TSRange *out) {
    const char *dash = strchr(text, '-');
    if (dash == NULL) return false;
    size_t start_length = (size_t)(dash - text);
    char start_text[64];
    char end_text[64];
    if (start_length == 0 || start_length >= sizeof(start_text) || strlen(dash + 1) >= sizeof(end_text)) {
        return false;
    }
    memcpy(start_text, text, start_length);
    start_text[start_length] = '\0';
    memcpy(end_text, dash + 1, strlen(dash + 1) + 1);
    Length start = length_zero();
    Length end = length_zero();
    if (!script_parse_length(start_text, &start) || !script_parse_length(end_text, &end)) return false;
    out->start_byte = start.bytes;
    out->start_point = start.extent;
    out->end_byte = end.bytes;
    out->end_point = end.extent;
    return true;
}

/* ts_tree_included_ranges: ranges = N, then one range per line. */
static void script_print_included_ranges(ScriptState *state, const TSTree *tree) {
    uint32_t count = 0;
    TSRange *ranges = ts_tree_included_ranges(tree, &count);
    sb_fmt(state->out, "ranges = %u\n", count);
    for (uint32_t i = 0; i < count; i++) {
        sb_fmt(state->out, "%u:%u:%u-%u:%u:%u\n",
            ranges[i].start_byte, ranges[i].start_point.row, ranges[i].start_point.column,
            ranges[i].end_byte, ranges[i].end_point.row, ranges[i].end_point.column);
    }
    ts_free(ranges);
}

