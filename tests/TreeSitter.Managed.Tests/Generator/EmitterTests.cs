using TreeSitter.Generator.Dump;
using TreeSitter.Generator.Emit;
using TreeSitter.Generator.Model;
using TreeSitter.Grammars.Json;
using TreeSitter.Tests.Oracle;
using Xunit;

namespace TreeSitter.Tests.Generator;

public class EmitterTests
{
    private const string JsonSource = "tree-sitter-json 254c42a6476413b776221e03982ac8ae159eeb72";

    private static string EmitJson() => new LiteralEmitter().Emit(
        GrammarModelBuilder.Build(CParserTests.GrammarParserC("Json")),
        new EmitOptions("Json", "TreeSitter.Grammars.Json", JsonSource));

    private static string RepositoryRoot() =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(CParserTests.GrammarParserC("Json"))!, "..", "..", "..", ".."));

    [OracleFact]
    public void CompiledJsonTablesMatchOracle()
    {
        NativeOracle.EnsureAvailable();
        Assert.Equal(NativeOracle.OracleDumpTables("json"), TableDumper.Dump(JsonGrammar.CreateTables()));
    }

    [OracleFact]
    public void CompiledCAndPythonTablesMatchOracle()
    {
        NativeOracle.EnsureAvailable();
        Assert.Equal(NativeOracle.OracleDumpTables("c"), TableDumper.Dump(TreeSitter.Grammars.C.CGrammar.CreateTables()));
        Assert.Equal(NativeOracle.OracleDumpTables("python"), TableDumper.Dump(TreeSitter.Grammars.Python.PythonGrammar.CreateTables()));
    }

    [Fact]
    public void CompiledJsonTablesMatchTheModel()
    {
        string model = TableDumper.Dump(GrammarModelBuilder.Build(CParserTests.GrammarParserC("Json")).Tables);
        Assert.Equal(model, TableDumper.Dump(JsonGrammar.CreateTables()));
    }

    [Fact]
    public void CreateTablesReturnsNewObjects()
    {
        Assert.NotSame(JsonGrammar.CreateTables().ParseTable, JsonGrammar.CreateTables().ParseTable);
    }

    [Fact]
    public void EmissionIsDeterministicAndCommitted()
    {
        string first = EmitJson();
        Assert.Equal(first, EmitJson());
        Assert.DoesNotContain("\r", first, StringComparison.Ordinal);
        string committed = File.ReadAllText(Path.Combine(RepositoryRoot(), "grammars", "Json", "Generated", "JsonLanguage.g.cs"));
        Assert.Equal(first, committed);
    }

    [Theory]
    [InlineData("C", "TreeSitter.Grammars.C")]
    [InlineData("Python", "TreeSitter.Grammars.Python")]
    public void EmitsGrammarsWithKeywordLexerAndExternalScanner(string grammar, string ns)
    {
        string code = new LiteralEmitter().Emit(GrammarModelBuilder.Build(CParserTests.GrammarParserC(grammar)), new EmitOptions(grammar, ns, null));
        Assert.Contains("KeywordLexFn = LexKeywords,", code, StringComparison.Ordinal);
        Assert.Contains("// Generated by ts2cs from parser.c. Do not edit.", code, StringComparison.Ordinal);
        if (grammar == "Python")
        {
            Assert.Contains("ExternalScannerStates = TableDecoder.Booleans(ExternalScannerStatesData),", code, StringComparison.Ordinal);
            Assert.Contains("ReservedWords = ReservedWordsData.ToArray(),", code, StringComparison.Ordinal);
            Assert.Contains("ExternalScannerScanIsSet = true,", code, StringComparison.Ordinal);
            Assert.Contains("ExternalScannerCreate = static () => new PythonScanner(),", code, StringComparison.Ordinal);
        }
        else
        {
            Assert.DoesNotContain("ExternalScannerCreate =", code, StringComparison.Ordinal);
        }
    }

    [Theory]
    [InlineData(null, "null")]
    [InlineData("end", "\"end\"")]
    [InlineData("a\"b\\c", "\"a\\\"b\\\\c\"")]
    [InlineData("\n\u007fé", "\"\\u000a\\u007f\\u00e9\"")]
    public void StringLiterals(string? value, string expected)
    {
        Assert.Equal(expected, LiteralEmitter.StringLiteral(value));
    }

    [Fact]
    public void BlobEmitterIsNotImplemented()
    {
        Assert.Throws<NotSupportedException>(() => new BlobEmitter().Emit(
            GrammarModelBuilder.Build(CParserTests.GrammarParserC("Json")), new EmitOptions("Json", "N", null)));
    }

    [Fact]
    public void CommandLine()
    {
        string dir = Path.Combine(Path.GetTempPath(), "ts2cs-test-" + Guid.NewGuid().ToString("N"));
        try
        {
            string parserC = CParserTests.GrammarParserC("Json");
            Assert.Equal(0, TreeSitter.Generator.Program.Main(["generate", parserC, "--name", "Json", "--namespace", "TreeSitter.Grammars.Json", "--out", dir, "--source", JsonSource]));
            Assert.Equal(EmitJson(), File.ReadAllText(Path.Combine(dir, "JsonLanguage.g.cs")));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate", parserC, "--name", "Json", "--namespace", "N", "--out", dir, "--tables", "blob"]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate", parserC, "--name", "Json", "--namespace", "N", "--out", dir, "--tables", "other"]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate", parserC, "--name", "Json"]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate", parserC, "--bogus", "x"]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate", parserC, "--name"]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["generate"]));
            Assert.Equal(0, TreeSitter.Generator.Program.Main(["dump-tables", parserC]));
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["dump-tables"]));

            string broken = Path.Combine(dir, "broken.c");
            File.WriteAllText(broken, "int x;\n");
            Assert.Equal(1, TreeSitter.Generator.Program.Main(["dump-tables", broken]));
        }
        finally
        {
            if (Directory.Exists(dir))
            {
                Directory.Delete(dir, recursive: true);
            }
        }
    }
}
