#!/usr/bin/env bash
# Builds the ts_oracle native shared library for the oracle test harness
# (tests only, never shipped).
#
#   libts_oracle.so / ts_oracle.dll / libts_oracle.dylib =
#       tests/Oracle/tree-sitter/lib/src/lib.c        (the whole pinned runtime)
#   + src/parser.c and src/scanner.c (if any) of every grammar under
#     grammars/*/upstream/src   (compiled in place, never copied or edited)
#   + tests/Oracle/shim/oracle.c
#   + a generated registration file oracle_grammars.c (not committed)
#
# Output: artifacts/oracle/<library>
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_LIB="$ROOT/tests/Oracle/tree-sitter/lib/src"
SHIM_DIR="$ROOT/tests/Oracle/shim"
GEN_DIR="$SHIM_DIR/generated"
OUT_DIR="$ROOT/artifacts/oracle"

CC="${CC:-clang}"
if ! command -v "$CC" >/dev/null 2>&1; then
  CC=gcc
fi

OS="$(uname -s | tr '[:upper:]' '[:lower:]')"
case "$OS" in
  linux*)   OUT_NAME="libts_oracle.so" ;;
  darwin*)  OUT_NAME="libts_oracle.dylib" ;;
  msys*|mingw*|cygwin*) OUT_NAME="ts_oracle.dll" ;;
  *)        OUT_NAME="libts_oracle.so" ;;
esac

mkdir -p "$OUT_DIR"
mkdir -p "$GEN_DIR"

# The shim includes "tree_sitter/api.h", "parser.h" and "language.h".
# Provide the vendored runtime headers under those names so they resolve
# regardless of whether a grammar source uses "tree_sitter/parser.h" or
# just "parser.h".
rm -rf "$GEN_DIR/tree_sitter"
mkdir -p "$GEN_DIR/tree_sitter"
cp "$SRC_LIB/parser.h" "$GEN_DIR/tree_sitter/parser.h"
cp "$SRC_LIB/language.h" "$GEN_DIR/tree_sitter/language.h"

# Generate the grammar registration file.
{
  echo '/* Generated by tools/build-oracle.sh from the upstream directory of each'
  echo '   grammar under grammars/. Do not edit. */'
  echo '#include "tree_sitter/api.h"'
  echo
} > "$GEN_DIR/oracle_grammars.c"

CFLAGS=(-O2 -std=c11 -Wall -Wextra -I "$GEN_DIR" -I "$SRC_LIB" \
  -I "$ROOT/tests/Oracle/tree-sitter/lib/include" \
  -include "$SHIM_DIR/oracle_wctype.h")

# The name of a grammar is the one of its language function in parser.c
# (tree_sitter_<name>), for example c_sharp for grammars/CSharp.
grammar_name() {
  grep -o 'TS_PUBLIC const TSLanguage \*tree_sitter_[a-z0-9_]*' "$1/parser.c" | sed 's/.*tree_sitter_//'
}

GRAMMAR_SRCS=()
for dir in "$ROOT/grammars"/*/upstream/src; do
  [ -d "$dir" ] || continue
  grammar_dir="$(dirname "$(dirname "$dir")")"
  name="$(grammar_name "$dir")"
  parser_c="$dir/parser.c"
  scanner_c="$dir/scanner.c"
  [ -f "$parser_c" ] || {
    echo "error: $parser_c not found (run tools/regen-grammar.sh for $name)" >&2
    exit 1
  }

  # Every grammar ships its own tree_sitter/ directory with the headers the
  # CLI v0.27.2 generated for it. The parser.h must match the pinned v0.27.2
  # runtime byte for byte - otherwise the grammar is incompatible with this
  # build of the oracle.
  grammar_parser_h="$dir/tree_sitter/parser.h"
  runtime_parser_h="$SRC_LIB/parser.h"
  if [ ! -f "$grammar_parser_h" ]; then
    echo "error: $grammar_parser_h not found" >&2
    exit 1
  fi
  if ! cmp -s "$grammar_parser_h" "$runtime_parser_h"; then
    echo "error: $grammar_parser_h does not match the pinned runtime $runtime_parser_h" >&2
    echo "       regenerate the grammar with tools/regen-grammar.sh" >&2
    exit 1
  fi

  # Compile the grammar's parser.c/scanner.c in place, with -I pointing at
  # the grammar's own src/ directory so quoted includes such as
  # "tree_sitter/array.h" resolve to the headers generated by the same CLI
  # v0.27.2 that produced the grammar, not to the grammar repo's vendored
  # copies.
  CFLAGS+=(-I "$(dirname "$dir")")
  GRAMMAR_SRCS+=("$parser_c")
  [ -f "$scanner_c" ] && GRAMMAR_SRCS+=("$scanner_c")

  echo "extern const TSLanguage *tree_sitter_${name}(void);" >> "$GEN_DIR/oracle_grammars.c"
  echo "static const TSLanguage *tree_sitter_${name}__create(void) {" >> "$GEN_DIR/oracle_grammars.c"
  echo "  return tree_sitter_${name}();" >> "$GEN_DIR/oracle_grammars.c"
  echo "}" >> "$GEN_DIR/oracle_grammars.c"
  echo >> "$GEN_DIR/oracle_grammars.c"
done

{
  echo 'const struct {'
  echo '  const char *name;'
  echo '  const TSLanguage *(*create)(void);'
  echo '} oracle_grammars[] = {'
} >> "$GEN_DIR/oracle_grammars.c"

first=1
for dir in "$ROOT/grammars"/*/upstream/src; do
  [ -d "$dir" ] || continue
  name="$(grammar_name "$dir")"
  if [ "$first" -eq 1 ]; then
    first=0
  else
    printf ',\n' >> "$GEN_DIR/oracle_grammars.c"
  fi
  printf '  { "%s", tree_sitter_%s__create }' "$name" "$name" >> "$GEN_DIR/oracle_grammars.c"
done
echo >> "$GEN_DIR/oracle_grammars.c"

{
  echo '};'
  echo
  echo 'const size_t oracle_grammar_count ='
  echo '    sizeof(oracle_grammars) / sizeof(oracle_grammars[0]);'
} >> "$GEN_DIR/oracle_grammars.c"

case "$OS" in
  msys*|mingw*|cygwin*) ;;
  *)
    # glibc hides le16toh/be16toh (endian.h) and fdopen (stdio.h POSIX)
    # behind __STRICT_ANSI__ under -std=c11; expose them via _DEFAULT_SOURCE.
    CFLAGS+=(-fPIC -D_DEFAULT_SOURCE) ;;
esac

OUT="$OUT_DIR/$OUT_NAME"

echo "==> building $OUT ($CC)"
# shellcheck disable=SC2086
$CC "${CFLAGS[@]}" -shared -o "$OUT" "$SRC_LIB/lib.c" ${GRAMMAR_SRCS[@]+"${GRAMMAR_SRCS[@]}"} \
  "$SHIM_DIR/oracle.c" "$GEN_DIR/oracle_grammars.c"

echo "==> done: $OUT"
